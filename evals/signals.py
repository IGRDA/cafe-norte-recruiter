ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "evals" / "cases" / "signals" / "turns.yaml"
# ``dev`` is the hand-written set the questions were tuned on; ``heldout`` is generated by
# another model (``evals/signals_generate.py``) and only scored.
CASE_SETS: dict[str, Path] = {
    "dev": FIXTURE,
    "heldout": ROOT / "evals" / "cases" / "signals" / "heldout.yaml",
}
RESULTS = ROOT / "evals" / "results" / "signals"
SYSTEMS: tuple[SignalSystem, ...] = ("regex", "production", "llm", "jev")
DEFAULT_SIGNAL_MODEL = "openai/gpt-4o-mini"
CALL_SECONDS = 10.0  # per classifier call; production uses 5 s, the experiment wants answers
CONCURRENCY = 4  # calls in flight per system
# Tokens per call for the printed estimate, rounded up from a dry count of the prompts.
TOKENS_PER_CALL: dict[SignalSystem, tuple[int, int]] = {
    "production": (450, 30),
    "llm": (650, 25),
    "jev": (350, 0),
}

QUESTIONS: dict[str, ChoiceQuestion] = {
    "sentiment": ChoiceQuestion(
        instructions="The tone of candidate_said, the job candidate's latest message to Ana, "
        "a recruiting assistant. Judge the words only, never the person.",
        criteria={
            "neutral": "Plain answers, questions, refusals or goodbyes, including a plain no.",
            "positive": "Clear enthusiasm or thanks.",
            "frustrated": "Annoyance, impatience, sarcasm, or feeling misunderstood or "
            "made to repeat.",
            "uncertain": "Hesitation, doubt or confusion about what to answer.",
        },
    ),
    "reply_language": ChoiceQuestion(
        instructions="The language Ana should use for her next reply. Keep session_language "
        "unless candidate_said asks to change language, says the candidate cannot follow "
        "session_language, or is written entirely in the other language. Mentioning a "
        "language, a borrowed word or two, or refusing a switch keeps session_language.",
        criteria={"es": "Spanish", "en": "English"},
    ),
}


def load_cases(path: Path = FIXTURE, only: Sequence[str] = ()) -> list[SignalCase]:
    cases = [SignalCase.model_validate(c) for c in yaml.safe_load(path.read_text())]
    unknown = set(only) - {c.id for c in cases}
    if unknown:
        raise ValueError(f"unknown signal cases: {', '.join(sorted(unknown))}")
    return [c for c in cases if not only or c.id in only]


def state_of(case: SignalCase) -> dict[str, str]:
    """What Jev and the ``llm`` system read: the same three facts."""
    return {
        "session_language": case.session_language,
        "ana_said": case.ana,
        "candidate_said": case.text,
    }


def llm_prompt() -> str:
    """The ``llm`` system's instructions, written from ``QUESTIONS`` so both systems are asked
    the same thing."""
    parts = [
        "You read one message a job candidate said to Ana, a recruiting assistant. Reply with "
        "one JSON object and nothing else: "
        + json.dumps({name: "|".join(q.criteria) for name, q in QUESTIONS.items()})
    ]
    for name, question in QUESTIONS.items():
        options = "\n".join(f"- {key}: {meaning}" for key, meaning in question.criteria.items())
        parts.append(f"{name}: {question.instructions}\n{options}")
    return "\n\n".join(parts)


# ---- systems -------------------------------------------------------------------------------------


class Classifier(Protocol):
    system: SignalSystem
    model: str

    async def classify(self, case: SignalCase, repetition: int) -> SignalPrediction: ...


class RegexClassifier:
    system: SignalSystem = "regex"
    model = "explicit_controls"

    async def classify(self, case: SignalCase, repetition: int) -> SignalPrediction:
        started = time.perf_counter()
        language = requested_language(explicit_controls(case.text), case.session_language)
        return SignalPrediction(
            case_id=case.id,
            system=self.system,
            repetition=repetition,
            reply_language=language,
            milliseconds=_since(started),
        )


class ProductionClassifier:
    """The shipped path, unchanged: no verdict (late, malformed, evidence not in the text) is
    what the runtime sees as no signal, so it scores as neutral."""

    system: SignalSystem = "production"

    def __init__(self, model: Model, prices: PriceTable) -> None:
        self.model = model.model_id
        self._analyzer = ModelSignalAnalyzer(model, deadline_seconds=CALL_SECONDS)
        self._prices = prices

    async def classify(self, case: SignalCase, repetition: int) -> SignalPrediction:
        started = time.perf_counter()
        analysis = await self._analyzer.analyze(TurnId(case.id), case.text, case.session_language)
        return SignalPrediction(
            case_id=case.id,
            system=self.system,
            repetition=repetition,
            sentiment=analysis.signal.sentiment if analysis.signal else "neutral",
            milliseconds=_since(started),
            cost_eur=_eur(self._prices, self.model, analysis.usage),
            error=None if analysis.usage is not None else "no_reply",
        )


class _Answer(BaseModel):
    model_config = ConfigDict(frozen=True, extra="ignore")

    sentiment: Sentiment
    reply_language: Language


class LlmClassifier:
    system: SignalSystem = "llm"

    def __init__(self, model: Model, prices: PriceTable) -> None:
        self.model = model.model_id
        self._model = model
        self._prices = prices
        self._system_prompt = llm_prompt()

    async def classify(self, case: SignalCase, repetition: int) -> SignalPrediction:
        messages = (
            ModelMessage(role="system", content=self._system_prompt),
            ModelMessage(role="user", content=json.dumps(state_of(case), ensure_ascii=False)),
        )
        parts: list[str] = []
        usage: ModelUsage | None = None
        started = time.perf_counter()
        error: str | None = None
        answer: _Answer | None = None
        try:
            async with asyncio.timeout(CALL_SECONDS):
                deadline = datetime.now(UTC) + timedelta(seconds=CALL_SECONDS)
                async for event in self._model.stream(messages, (), deadline=deadline):
                    if isinstance(event, ModelText):
                        parts.append(event.text)
                    elif isinstance(event, ModelUsage):
                        usage = event
            answer = _Answer.model_validate_json(_strip_fence("".join(parts)))
        except TimeoutError:
            error = "timeout"
        except ServiceError as failure:
            error = failure.code
        except ValidationError:
            error = "malformed"
        return SignalPrediction(
            case_id=case.id,
            system=self.system,
            repetition=repetition,
            sentiment=answer.sentiment if answer else None,
            reply_language=answer.reply_language if answer else None,
            milliseconds=_since(started),
            cost_eur=_eur(self._prices, self.model, usage),
            error=error,
        )


class JevClassifier:
    system: SignalSystem = "jev"

    def __init__(self, client: JevClient, usd_per_eur: float) -> None:
        self.model = client.model
        self._client = client
        self._usd_per_eur = usd_per_eur

    async def classify(self, case: SignalCase, repetition: int) -> SignalPrediction:
        started = time.perf_counter()
        try:
            decision = await self._client.decide(state_of(case), QUESTIONS)
        except JevError as failure:
            return SignalPrediction(
                case_id=case.id,
                system=self.system,
                repetition=repetition,
                milliseconds=_since(started),
                error=failure.code,
            )
        sentiment = decision.answers["sentiment"]
        language = decision.answers["reply_language"]
        if sentiment.choice not in QUESTIONS["sentiment"].criteria or (
            language.choice not in QUESTIONS["reply_language"].criteria
        ):
            return SignalPrediction(
                case_id=case.id,
                system=self.system,
                repetition=repetition,
                milliseconds=_since(started),
                error="unknown_choice",
            )
        return SignalPrediction(
            case_id=case.id,
            system=self.system,
            repetition=repetition,
            sentiment=sentiment.choice,
            sentiment_probabilities=sentiment.probabilities,
            reply_language=language.choice,
            language_probabilities=language.probabilities,
            milliseconds=_since(started),
            cost_eur=decision.cost_usd / self._usd_per_eur,
        )


async def run_signals(
    cases: Sequence[SignalCase], classifier: Classifier, *, repeat: int
) -> list[SignalPrediction]:
    """Every case ``repeat`` times, at most ``CONCURRENCY`` calls in flight."""
    gate = asyncio.Semaphore(CONCURRENCY)

    async def one(case: SignalCase, repetition: int) -> SignalPrediction:
        async with gate:
            return await classifier.classify(case, repetition)

    return list(
        await asyncio.gather(*(one(case, r) for r in range(1, repeat + 1) for case in cases))
    )


def _since(started: float) -> int:
    return int((time.perf_counter() - started) * 1000)


def _eur(prices: PriceTable, model: str, usage: ModelUsage | None) -> float | None:
    if usage is None:
        return None
    records = token_usage(
        SessionId("signals"), None, model, usage.input_tokens, usage.output_tokens, estimated=False
    )
    cost = estimate(SessionId("signals"), records, prices)
    return None if cost.missing_prices else cost.marginal_eur


def _strip_fence(raw: str) -> str:
    body = raw.strip()
    if body.startswith("```"):
        body = body.split("\n", 1)[-1].rsplit("```", 1)[0]
    return body.strip()


def usd_per_eur() -> float:
    return float(yaml.safe_load(PRICES_FILE.read_text(encoding="utf-8"))["usd_per_eur"])


# ---- command -------------------------------------------------------------------------------------


def estimate_eur(
    systems: Sequence[SignalSystem], signal_model: str, calls: int, prices: PriceTable
) -> tuple[float, list[str]]:
    """The paid systems' spend for ``calls`` calls each, and the models with no price."""
    total, unpriced = 0.0, []
    for system in systems:
        if system == "regex":
            continue
        tokens_in, tokens_out = TOKENS_PER_CALL[system]
        if system == "jev":
            total += calls * tokens_in * USD_PER_INPUT_TOKEN / usd_per_eur()
            continue
        records = token_usage(
            SessionId("estimate"),
            None,
            model_id(signal_model),
            calls * tokens_in,
            calls * tokens_out,
            estimated=True,
        )
        cost = estimate(SessionId("estimate"), records, prices)
        total += cost.marginal_eur
        unpriced += [label for label in cost.missing_prices if label not in unpriced]
    return total, unpriced


def signals_main(args: argparse.Namespace, env: Mapping[str, str] | None = None) -> int:
    env = env if env is not None else os.environ
    try:
        cases = load_cases(CASE_SETS[args.cases], only=args.only)
    except ValueError as error:
        print(error)
        return 1
    systems: list[SignalSystem] = list(args.systems)
    repeat = args.repeat or 2
    prices = load_prices()
    paid = [s for s in systems if s != "regex"]
    eur, unpriced = estimate_eur(paid, args.signal_model, len(cases) * repeat, prices)
    print(
        f"signals ({args.cases}): {len(cases)} cases × {repeat} repetitions; paid systems "
        f"{', '.join(paid) or 'none'}: estimated €{eur:.4f}"
        + (f"; NO PRICE for {', '.join(unpriced)}" if unpriced else "")
    )
    if paid and not args.yes:
        print("Nothing paid was called: add --yes to spend. Running regex only.")
        systems = [s for s in systems if s == "regex"]
    missing = [
        key
        for system, key in (("jev", "OPENROUTER_API_KEY"),)
        if system in systems and not env.get(key)
    ]
    if missing:
        print(f"{', '.join(missing)} is required for jev; see evals/README.md (signals).")
        return 2
    report = asyncio.run(_run(systems, cases, repeat, args.signal_model, prices, env))
    print(render_markdown(report, cases).split("\n## ", 1)[0])
    if args.yes and paid:
        out = Path(args.out or RESULTS)
        out.mkdir(parents=True, exist_ok=True)
        stem = out / f"{report.generated_at[:16].replace(':', '')}-{args.cases}-{'-'.join(systems)}"
        stem.with_suffix(".md").write_text(render_markdown(report, cases))
        stem.with_suffix(".json").write_text(render_json(report))
        print(f"wrote {stem}.md and .json")
    return 0


async def _run(
    systems: Sequence[SignalSystem],
    cases: Sequence[SignalCase],
    repeat: int,
    signal_model: str,
    prices: PriceTable,
    env: Mapping[str, str],
) -> SignalsReport:
    async with httpx.AsyncClient() as http:
        classifiers: list[Classifier] = []
        jev: JevClient | None = None
        for system in systems:
            if system == "regex":
                classifiers.append(RegexClassifier())
            elif system == "jev":
                jev = JevClient(env["OPENROUTER_API_KEY"], model=env.get("JEV_MODEL", JEV_MODEL))
                classifiers.append(JevClassifier(jev, usd_per_eur()))
            else:
                model = model_from_env(signal_model, env)
                if isinstance(model, ChatCompletionsModel):
                    model.bind_client(http)  # a warm connection, as in the server
                cls = ProductionClassifier if system == "production" else LlmClassifier
                classifiers.append(cls(model, prices))
        try:
            summaries, predictions = [], []
            for classifier in classifiers:
                found = await run_signals(cases, classifier, repeat=repeat)
                predictions += found
                summaries.append(summarize(classifier.system, classifier.model, cases, found))
        finally:
            if jev is not None:
                await jev.aclose()
    return SignalsReport(
        generated_at=datetime.now(UTC).isoformat(timespec="seconds"),
        cases=len(cases),
        repeat=repeat,
        prompt_version=PROMPT_VERSION,
        systems=tuple(summaries),
        predictions=tuple(predictions),
    )
